/** Вид документа в архиве. Регламент пп. 28, 58, 66, 70. */
export type DocumentKind =
  | 'Акт приема-передачи'
  | 'Технический АВР'     // п. 66: подписывают филиал и Заказчик
  | 'АВР'                 // пп. 70, 91: формирует СП ЦА, ответственное за расчёты
  | 'ТУ'
  | 'ПСД (РП)'
  | 'Договор'
  | 'Распоряжение'
  | 'КП'
  | 'Приложение';

/**
 * Форма акта — реквизит справочника, а не константа.
 * Пункт 70 относит типовую форму № 2В к подрядным работам (СМР); для услуг
 * (ТУ, ПСД) применяется Р-1, о которой говорит ТЗ. Технический АВР филиала —
 * по Приложению 6; акт приёма-передачи — в произвольной форме (п. 58).
 */
export type ActForm = '2В' | 'Р-1' | 'Прил. 6' | 'произвольная';

/** Позиция заявки: одна услуга с параметрами. Регламент п. 7.5 — услуг может быть несколько. */
export type RequestService = {
  service: Service;
  placement: Placement;
  params: Record<string, unknown>;
  tariffId?: string | null;
  tariffQuantity?: number | null;
  /** Номер основания для СМР: утверждённая ПСД либо договор (Регламент п. 53). */
  basisReference?: string | null;
};

/** Позиция прейскуранта. Регламент п. 18 — Прейскурант размещён на сайте Общества. */
export type Tariff = {
  id: string;
  service: Service;
  name: string;
  unit: string;
  amount: number;
  /** Основание: пункт Прейскуранта либо иной документ. */
  source: string;
  effectiveFrom: string;
  effectiveTo?: string | null;
};

/** Рабочий календарь РК: переносы и праздники. */
export type WorkCalendar = {
  /** Нерабочие дни сверх выходных (ISO-даты). */
  holidays: string[];
  /** Рабочие дни, выпавшие на выходные (переносы). */
  workingDays: string[];
};

export const EMPTY_CALENDAR: WorkCalendar = { holidays: [], workingDays: [] };
